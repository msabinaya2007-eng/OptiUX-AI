"use client";

import { useAnalysis } from "@/lib/analysis-context";
import { FileText } from "lucide-react";
import { toast } from "sonner";

export function PDFExport() {
  const { currentSession } = useAnalysis();
  const result = currentSession?.result;

  const handleExport = async () => {
    if (!result) {
      toast.error("No results to export");
      return;
    }

    try {
      const { jsPDF } = await import("jspdf");
      const doc = new jsPDF();
      const pageWidth = doc.internal.pageSize.getWidth();
      let y = 20;

      const addPageIfNeeded = (needed: number) => {
        if (y + needed > 270) {
          doc.addPage();
          y = 20;
        }
      };

      // Header
      doc.setFontSize(20);
      doc.setFont("helvetica", "bold");
      doc.text("OptiUX-AI", 14, y);
      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");
      doc.text("UX Analysis Report", pageWidth - 14, y, { align: "right" });
      y += 8;

      doc.setDrawColor(200);
      doc.line(14, y, pageWidth - 14, y);
      y += 10;

      // Project Info
      if (currentSession?.context?.projectName) {
        doc.setFontSize(11);
        doc.setFont("helvetica", "bold");
        doc.text(`Project: ${currentSession.context.projectName}`, 14, y);
        y += 7;
      }
      doc.setFontSize(9);
      doc.setFont("helvetica", "normal");
      doc.text(
        `Date: ${new Date(currentSession?.timestamp || "").toLocaleDateString()}`,
        14,
        y
      );
      if (currentSession?.url) {
        doc.text(`URL: ${currentSession.url}`, 14, y + 5);
        y += 5;
      }
      y += 10;

      // Overall Score
      doc.setFontSize(14);
      doc.setFont("helvetica", "bold");
      doc.text(`Overall UX Score: ${result.overallScore}/100`, 14, y);
      y += 10;

      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");
      const summaryLines = doc.splitTextToSize(result.summary, pageWidth - 28);
      doc.text(summaryLines, 14, y);
      y += summaryLines.length * 5 + 8;

      // Category Scores
      doc.setFontSize(12);
      doc.setFont("helvetica", "bold");
      doc.text("Category Scores", 14, y);
      y += 8;

      const catLabels: Record<string, string> = {
        accessibility: "Accessibility",
        usability: "Usability",
        visualHierarchy: "Visual Hierarchy",
        interactionCost: "Interaction Cost",
        cognitiveLoad: "Cognitive Load",
      };

      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");
      for (const [key, value] of Object.entries(result.categories)) {
        doc.text(`${catLabels[key] || key}: ${value}/100`, 20, y);
        y += 6;
      }
      y += 6;

      // Strengths
      addPageIfNeeded(20);
      doc.setFontSize(12);
      doc.setFont("helvetica", "bold");
      doc.text("Strengths", 14, y);
      y += 8;

      doc.setFontSize(9);
      doc.setFont("helvetica", "normal");
      for (const s of result.strengths) {
        addPageIfNeeded(8);
        doc.text(`+ ${s}`, 20, y);
        y += 5;
      }
      y += 6;

      // Issues
      addPageIfNeeded(20);
      doc.setFontSize(12);
      doc.setFont("helvetica", "bold");
      doc.text(`UX Issues (${result.issues.length})`, 14, y);
      y += 8;

      for (const issue of result.issues) {
        addPageIfNeeded(25);
        doc.setFontSize(9);
        doc.setFont("helvetica", "bold");
        doc.text(
          `[${issue.severity.toUpperCase()}] ${issue.title} — ${issue.category}`,
          20,
          y
        );
        y += 5;
        doc.setFont("helvetica", "normal");
        const descLines = doc.splitTextToSize(issue.description, pageWidth - 40);
        doc.text(descLines, 24, y);
        y += descLines.length * 4 + 2;
        const recLines = doc.splitTextToSize(
          `Recommendation: ${issue.recommendation}`,
          pageWidth - 40
        );
        doc.text(recLines, 24, y);
        y += recLines.length * 4 + 4;
      }

      // Recommendations
      addPageIfNeeded(20);
      doc.setFontSize(12);
      doc.setFont("helvetica", "bold");
      doc.text("Recommendations", 14, y);
      y += 8;

      doc.setFontSize(9);
      for (const rec of result.recommendations) {
        addPageIfNeeded(15);
        doc.setFont("helvetica", "bold");
        doc.text(`[${rec.impact}] ${rec.title}`, 20, y);
        y += 5;
        doc.setFont("helvetica", "normal");
        const lines = doc.splitTextToSize(rec.description, pageWidth - 40);
        doc.text(lines, 24, y);
        y += lines.length * 4 + 4;
      }

      // Footer on last page
      const lastPageHeight = doc.internal.pageSize.getHeight();
      doc.setFontSize(8);
      doc.setFont("helvetica", "italic");
      doc.text(
        "Generated by OptiUX-AI",
        pageWidth / 2,
        lastPageHeight - 10,
        { align: "center" }
      );

      doc.save(`optiux-report-${Date.now()}.pdf`);
      toast.success("PDF exported successfully");
    } catch {
      toast.error("Failed to export PDF");
    }
  };

  if (!result) return null;

  return (
    <button
      onClick={handleExport}
      className="inline-flex items-center gap-2 px-4 py-2 text-sm font-medium border border-border rounded-lg hover:bg-muted transition-colors"
    >
      <FileText className="w-4 h-4" />
      Export PDF
    </button>
  );
}
